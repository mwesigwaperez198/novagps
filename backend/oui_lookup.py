def lookup_vendor(mac_address: str | None) -> str | None:
    """Return the vendor name for a MAC address, or None if not found."""
    if not mac_address:
        return None
    normalized = mac_address.upper().strip()
    prefix = normalized[:8]
    if prefix in OUI_TABLE:
        return OUI_TABLE[prefix]
    prefix = normalized[:5]
    if prefix in OUI_TABLE:
        return OUI_TABLE[prefix]
    return None


def normalize_mac(mac: str | None) -> str | None:
    """Normalize a MAC address to uppercase colon-separated format."""
    if not mac:
        return None
    cleaned = mac.replace("-", ":").replace(".", ":").upper().strip()
    parts = [p for p in cleaned.split(":") if p]
    if len(parts) != 6:
        return None
    return ":".join(parts)
